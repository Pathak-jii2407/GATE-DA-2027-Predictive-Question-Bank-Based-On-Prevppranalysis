def _finish(Q):
    for i, it in enumerate(Q):
        if "section" not in it:
            it["section"] = "GA" if i < 10 else "DA"
    out = uniq(Q)
    if len(out) != 65:
        raise AssertionError("unique %d from %d" % (len(out), len(Q)))
    if sum(x["marks"] for x in out) != 100:
        raise AssertionError("marks %d" % sum(x["marks"] for x in out))
    seq = [x["marks"] for x in out]
    if seq != [1] * 5 + [2] * 5 + [1] * 25 + [2] * 30:
        raise AssertionError("mark order %s" % seq)
    return out


